def top_split(expr):
    """split expr at top-level ' + ' / ' - ' -> (list of terms, list of ops)"""
    terms, ops, depth, cur, i = [], [], 0, "", 0
    while i < len(expr):
        ch = expr[i]
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if depth == 0 and expr[i:i + 3] in (" + ", " - "):
            terms.append(cur.strip()); ops.append(expr[i + 1]); cur = ""; i += 3; continue
        cur += ch
        i += 1
    terms.append(cur.strip())
    return terms, ops


