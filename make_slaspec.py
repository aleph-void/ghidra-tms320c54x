def apply_overrides(text):
    out = []
    for l in text.split('\n'):
        for k, b in OVERRIDES.items():
            if l.startswith(':') and l[:l.find(' is ')].split() == k.split():
                i = l.index('{'); j = l.rindex('}')
                l = l[:i + 1] + ' ' + b + ' ' + l[j:]
                break
        out.append(l)
    return '\n'.join(out)


