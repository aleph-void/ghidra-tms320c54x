#!/usr/bin/env python3
"""Generate data/languages/TMS320C54x.slaspec, the Ghidra SLEIGH spec for the TI TMS320C54x.

Encodings follow the GNU binutils opcode table (opcodes/tic54x-opc.c), checked against the
PSR-500/600 DSP firmware with an independent disassembler built from the same table.

Modelling choices (see README.md):
- Program, data and I/O are separate word-addressed spaces (16-bit words, big-endian).
- Accumulators A/B are 40-bit values held sign-extended in 64-bit registers; AL/AH/AG views.
- Loads into an accumulator sign-extend (SXM=1), the usual setting; OVM saturation, rounding
  details, circular and bit-reversed addressing are simplified (noted per constructor).
- Direct addressing uses DP unless the context bit cplmode is set (SSBX/RSBX CPL set it for
  the following code), then SP.
- RPT/RPTB/RPTZ only set the repeat registers; the decompiler doesn't model repetition.
"""
